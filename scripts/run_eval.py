"""Score every policy on the call queue; write results/metrics.json and results/report.md.

    python scripts/run_eval.py              # recompute and write
    python scripts/run_eval.py --check      # recompute, fail if committed results differ, then gate (CI)
    python scripts/run_eval.py --summary    # headline numbers from results/metrics.json

The gate fails if a guardrail breaks (a guarded offer that is ineligible or over the cost limit, a
talk track that leaks contact details or makes a forbidden promise reaching the desk) or if the main
configuration drops below floors set once from the measured run.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from retention.data import queue  # noqa: E402
from retention.evaluate import ISSUES, evaluate  # noqa: E402
from retention.offers import MAX_COST, cost, eligible  # noqa: E402

OUT = ROOT / "results"
MAIN = "gemma4-e2b.hybrid.guarded"
FLOORS = {"main_share_of_oracle": 0.0, "uplift_share_of_oracle": 0.0}  # set once from the measured run


def pct(r: dict | None) -> str:
    return "n/a" if not r else f"{r['rate'] * 100:.1f}% ({r['k']}/{r['n']})"


def report(m: dict) -> str:
    s = m["suite"]
    L = ["# Evaluation report (generated by scripts/run_eval.py, do not edit)", "",
         (f"Synthetic customers of the fictional operator Halvorsk Mobile. Models learn from a past randomised "
          f"campaign over {s['train']:,} customers; policies are scored on a call queue of the {s['queue']} "
          f"highest-risk customers out of {s['test']:,} held-out customers, using the simulator's true expected "
          f"value of each offer (two years of margin saved minus offer cost). Queue churn drivers: "
          f"{s['queue_drivers']}; {s['queue_injected']} queue notes carry an injected instruction. Churn model AUC on "
          f"simulated outcomes: {s['churn_auc']['account_data']} (account data), "
          f"{s['churn_auc']['with_note_keywords']} (plus note keywords). Values are in synthetic currency units."), "",
         "| Policy | Net value | Share of oracle | Offers made | Customers saved | Offer spend | To leavers | To settled |",
         "|---|---|---|---|---|---|---|---|"]
    for k, p in m["policies"].items():
        L.append(f"| {k} | {p['net_value']:,.1f} | {p['share_of_oracle'] * 100:.1f}% | {pct(p['offers_made'])} | "
                 f"{p['customers_saved']} | {p['offer_spend']:,.1f} | {p['offers_to_leavers']} | {p['offers_to_settled']} |")
    L += ["", "## Paired comparisons (same customers; paired bootstrap 95% interval of the total difference)", "",
          "| Comparison | Difference | 95% interval | Better for | Worse for |", "|---|---|---|---|---|"]
    L += [f"| {p['first']} vs {p['second']} | {p['diff']:+,.1f} | {p['ci95'][0]:+,.1f} to {p['ci95'][1]:+,.1f} | "
          f"{p['better']} | {p['worse']} |" for p in m["paired"].values()]
    L += ["", "## Offer mix", "", "| Policy | " + " | ".join(next(iter(m["policies"].values()))["mix"]) + " |",
          "|---|" + "---|" * len(next(iter(m["policies"].values()))["mix"])]
    L += [f"| {k} | " + " | ".join(str(v) for v in p["mix"].values()) + " |" for k, p in m["policies"].items()]
    L += ["", "## Copilot replies before the guard", "", "| Config | Passed the guard | " + " | ".join(ISSUES) +
          " | Injected notes | Followed the injection | p50 s |", "|---|---|" + "---|" * (len(ISSUES) + 3)]
    for k, x in m["llm"].items():
        L.append(f"| {k} | {pct(x['raw_ok'])} | " + " | ".join(str(x["issues"][i]) for i in ISSUES) +
                 f" | {x['injected']} | {x['injection_followed']} | {x['seconds_p50']} |")
    L += ["", "## Offer rate by group (no policy reads age band or region)", ""]
    for k, p in m["policies"].items():
        f = p["fairness"]
        L.append(f"- {k}: largest gap across age bands {f['age_band']['max_gap'] * 100:.1f} points, across regions "
                 f"{f['region']['max_gap'] * 100:.1f} points")
    return "\n".join(L) + "\n"


def guarded_offers_ok() -> list[str]:
    bad = []
    by = {c["id"]: c for c in queue()}
    for f in (ROOT / "data" / "runs").glob("*.jsonl"):
        for line in f.read_text().splitlines():
            r = json.loads(line)
            c = by[r["id"]]
            if not eligible(r["offer"], c)[0] or cost(r["offer"], c) > MAX_COST:
                bad.append(f"{f.stem}/{r['id']}: guarded offer {r['offer']} breaks the offer rules")
    return bad


def gate(m: dict) -> list[str]:
    p, bad = m["policies"], guarded_offers_ok()
    if p["uplift"]["share_of_oracle"] < FLOORS["uplift_share_of_oracle"]:
        bad.append("uplift model below its floor")
    if MAIN not in p:
        return [*bad, f"no runs for {MAIN}"]
    if p[MAIN]["share_of_oracle"] < FLOORS["main_share_of_oracle"]:
        bad.append(f"{MAIN} below floor")
    return bad


def dump(m: dict) -> str:
    return json.dumps(m, indent=1) + "\n"


def main() -> int:
    args = set(sys.argv[1:])
    if "--summary" in args:
        m = json.loads((OUT / "metrics.json").read_text())
        for k, p in m["policies"].items():
            print(f"{k:34s} net {p['net_value']:9.1f}  share {p['share_of_oracle']:.3f}  offers {p['offers_made']['rate']:.2f}")
        for k, p in m["paired"].items():
            print(f"{k:28s} diff {p['diff']:+.1f} [{p['ci95'][0]:+.1f}, {p['ci95'][1]:+.1f}] better {p['better']} worse {p['worse']}")
        for k, x in m["llm"].items():
            print(k, "raw ok", x["raw_ok"]["rate"], x["issues"], "inj", x["injected"], x["injection_followed"])
        return 0
    m = evaluate()
    if "--check" in args:
        if (OUT / "metrics.json").read_text() != dump(m) or (OUT / "report.md").read_text() != report(m):
            print("results/ differ from a fresh replay; run scripts/run_eval.py and commit")
            return 1
    else:
        OUT.mkdir(exist_ok=True)
        (OUT / "metrics.json").write_text(dump(m))
        (OUT / "report.md").write_text(report(m))
    bad = gate(m)
    for b in bad:
        print("GATE FAIL:", b)
    print("gate:", "FAIL" if bad else "pass")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
